export type ErrorCode = keyof typeof ERRORS

export const errorArea = (code: ErrorCode): ErrorArea => code.slice(0, 3) as ErrorArea

/** The text with its `{parameters}` filled in; one left out stays as it is, braces and all. */
export function errorMessage(code: ErrorCode, params: Record<string, string> = {}): string {
  return ERRORS[code].text.replace(/\{(\w+)\}/g, (all, name: string) => params[name] ?? all)
}

/** How a coded error travels to the window: «КОД: текст» (split again by splitErrorCode in the renderer). */
export function codedMessage(code: ErrorCode, params?: Record<string, string>): string {
  return `${code}: ${errorMessage(code, params)}`
}

/** A catalog code before the message («KEY-08: Достигнут лимит…»), split from the text. */
export function splitErrorCode(message: string): { code: ErrorCode | null; text: string } {
  const m = /^([A-Z][A-Z0-9]{2}-\d{2}):\s+/.exec(message)
  return m && m[1] in ERRORS ? { code: m[1] as ErrorCode, text: message.slice(m[0].length) } : { code: null, text: message }
}

/** A journal line: «[КОД] текст», or the code with the details only the journal gets. */
export function logMessage(code: ErrorCode, detail?: string): string {
  return `[${code}] ${detail ?? ERRORS[code].text}`
}
